    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
     try {
        if (txtNik.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data pelanggan dari tabel!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
                "Apakah Anda yakin ingin menghapus data pelanggan ini?", "Konfirmasi Hapus", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM tb_pelanggan WHERE nik = '" + txtNik.getText() + "'";
            Core.DML.EQuery(sql);
            javax.swing.JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Dihapus!");
            
            btnClearActionPerformed(evt);
            tampilTable();
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
    }   // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed



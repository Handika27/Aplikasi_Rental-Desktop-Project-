    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {
    if (txtNik.getText().isEmpty() || txtNama.getText().isEmpty() || txtTelp.getText().isEmpty() || txtAlamat.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Semua data harus diisi terlebih dahulu!");
        return;
    }

    String sql = "INSERT INTO tb_pelanggan (nik, nama_pelanggan, no_telp, alamat) VALUES ('" 
            + txtNik.getText() + "', '" 
            + txtNama.getText() + "', '" 
            + txtTelp.getText() + "', '" 
            + txtAlamat.getText() + "')";
    
    int i = Core.DML.EQuery(sql);
    
    if (i > 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Disimpan!");
        txtNik.setText("");
        txtNama.setText("");
        txtTelp.setText("");
        txtAlamat.setText("");
        txtNik.setEnabled(true);
        tampilTable(); 
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data! (Kemungkinan NIK sudah terdaftar)");
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tbPelangganMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbPelangganMouseClicked
try {
    int baris = tbPelanggan.getSelectedRow();
    if (baris != -1) {
        txtNik.setText(tbPelanggan.getValueAt(baris, 0).toString());
        txtNama.setText(tbPelanggan.getValueAt(baris, 1).toString());
        txtTelp.setText(tbPelanggan.getValueAt(baris, 2).toString());
        txtAlamat.setText(tbPelanggan.getValueAt(baris, 3).toString());
        
        // Kunci NIK agar primary key tidak bisa diubah saat mode update
        txtNik.setEnabled(false); 
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_tbPelangganMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
try {
        if (txtNik.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data pelanggan dari tabel!");
            return;
        }

        String sql = "UPDATE tb_pelanggan SET nama = '" + txtNama.getText() 
                + "', no_telp = '" + txtTelp.getText() 
                + "', alamat = '" + txtAlamat.getText() 
                + "' WHERE nik = '" + txtNik.getText() + "'";

        Core.DML.EQuery(sql);
        javax.swing.JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Diubah!");
        
        btnClearActionPerformed(evt);
        tampilTable();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed


    public void tampilTable() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
    model.addColumn("ID Sewa");
    model.addColumn("NIK");
    model.addColumn("Nopol");
    model.addColumn("Tgl Sewa");
    model.addColumn("Durasi");
    model.addColumn("Total Harga");

    try {
        // Menggunakan koneksi database yang sama dengan FrKendaraan
        java.sql.Connection conn = new myConnection.DB0().getConnection();
        java.sql.Statement st = conn.createStatement();
        
        // Ambil data transaksi yang statusnya MASIH 'Sedang Disewa'
        String sql = "SELECT * FROM tb_sewa WHERE status_sewa = 'Sedang Disewa'";
        java.sql.ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_sewa"),
                rs.getString("nik"),
                rs.getString("nopol"),
                rs.getString("tgl_sewa"),
                rs.getString("durasi"),
                rs.getString("total_harga")
            });
        }
        tbPengembalian.setModel(model);
        
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data pengembalian: " + e.getMessage());
    }

}


    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
int row = tbPengembalian.getSelectedRow();
    if (row == -1 || txtIdTransaksi.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Pilih transaksi dari tabel yang akan dikembalikan!");
        return;
    }

    try {
        String idSewa = txtIdTransaksi.getText();
        String nopol = tbPengembalian.getValueAt(row, 2).toString();

        // 1. Ubah status transaksi di tb_sewa menjadi 'Selesai'
        String sqlUpdateSewa = "UPDATE tb_sewa SET status_sewa = 'Selesai' WHERE id_sewa = '" + idSewa + "'";
        Core.DML.EQuery(sqlUpdateSewa);

        // 2. Ubah status kendaraan di tb_kendaraan kembali menjadi 'Tersedia'
        String sqlUpdateKendaraan = "UPDATE tb_kendaraan SET status = 'Tersedia' WHERE nopol = '" + nopol + "'";
        Core.DML.EQuery(sqlUpdateKendaraan);

        JOptionPane.showMessageDialog(this, "Pengembalian Kendaraan Berhasil Diproses!");

        // Reset inputan & Refresh isi tabel
        txtIdTransaksi.setText("");
        txtDenda.setText("0");
        tampilTable();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal memproses pengembalian: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnProsesActionPerformed

    private void tbPengembalianMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbPengembalianMouseClicked
    int row = tbPengembalian.getSelectedRow();
    if (row != -1) {
        try {
            String idSewa = tbPengembalian.getValueAt(row, 0).toString();
            String tglSewaStr = tbPengembalian.getValueAt(row, 3).toString();
            int durasi = Integer.parseInt(tbPengembalian.getValueAt(row, 4).toString());
            int totalHarga = Integer.parseInt(tbPengembalian.getValueAt(row, 5).toString());

            // 1. Masukkan ID Transaksi ke kotak input
            txtIdTransaksi.setText(idSewa);

            // 2. Hitung Denda Otomatis (Jika Keterlambatan Terjadi)
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            Date tglSewa = sdf.parse(tglSewaStr);

            Calendar cal = Calendar.getInstance();
            cal.setTime(tglSewa);
            cal.add(Calendar.DAY_OF_MONTH, durasi);
            Date tglJatuhTempo = cal.getTime();

            Date tglHariIni = new Date();

            if (tglHariIni.after(tglJatuhTempo)) {
                long selisihMillis = tglHariIni.getTime() - tglJatuhTempo.getTime();
                long hariTerlambat = selisihMillis / (1000 * 60 * 60 * 24);

                int hargaPerHari = totalHarga / durasi;
                int denda = (int) (hariTerlambat * hargaPerHari);

                txtDenda.setText(String.valueOf(denda));
            } else {
                txtDenda.setText("0");
            }

        } catch (Exception e) {
            txtDenda.setText("0");
        }
    }    // TODO add your handling code here:
    }//GEN-LAST:event_tbPengembalianMouseClicked



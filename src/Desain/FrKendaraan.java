    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
     try {
        if (txtPlat.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data dari tabel yang akan dihapus!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, 
                "Apakah Anda yakin ingin menghapus kendaraan ini?", "Konfirmasi Hapus", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String sql = "DELETE FROM tb_kendaraan WHERE nopol = '" + txtPlat.getText() + "'";
            Core.DML.EQuery(sql);
            javax.swing.JOptionPane.showMessageDialog(this, "Data Kendaraan Berhasil Dihapus!");
            
            btnClearActionPerformed(evt);
            tampilTable();
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
    }   // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
     try {
        if (txtPlat.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data dari tabel yang akan diubah!");
            return;
        }

        String sql = "UPDATE tb_kendaraan SET merk = '" + txtMerk.getText() 
                + "', jenis = '" + cbJenis.getSelectedItem().toString() 
                + "', harga = " + txtHarga.getText() 
                + " WHERE nopol = '" + txtPlat.getText() + "'";

        Core.DML.EQuery(sql);
        javax.swing.JOptionPane.showMessageDialog(this, "Data Kendaraan Berhasil Diubah!");
        
        btnClearActionPerformed(evt); // Reset form
        tampilTable(); // Refresh tabel
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage());
    }   // TODO add your handling code here:
    }//GEN-LAST:event_btnUpdateActionPerformed



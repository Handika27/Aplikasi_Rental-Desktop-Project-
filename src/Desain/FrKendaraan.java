    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {
    // Validasi agar tidak ada kotak yang kosong
    if (txtPlat.getText().isEmpty() || txtMerk.getText().isEmpty() || txtHarga.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Semua data harus diisi terlebih dahulu!");
        return;
    }

    String jenis = cbJenis.getSelectedItem().toString();
    
    // Query Insert disesuaikan dengan nama kolom asli di phpMyAdmin
    String sql = "INSERT INTO tb_kendaraan (nopol, merk_kendaraan, jenis, harga_sewa, status) VALUES ('" 
            + txtPlat.getText() + "', '" 
            + txtMerk.getText() + "', '" 
            + jenis + "', '" 
            + txtHarga.getText() + "', 'Tersedia')";
    
    int i = Core.DML.EQuery(sql);
    
    if (i > 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Data Kendaraan Berhasil Disimpan!");
        
        // Kosongkan form setelah berhasil
        txtPlat.setText("");
        txtMerk.setText("");
        txtHarga.setText("");
        cbJenis.setSelectedIndex(0);
        
        // Refresh tabel
        tampilTable(); 
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal menyimpan data! (Kemungkinan Plat Nomor sudah terdaftar)");
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}     // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tbKendaraanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbKendaraanMouseClicked
try {
    int baris = tbKendaraan.getSelectedRow();
    if (baris != -1) {
        txtPlat.setText(tbKendaraan.getValueAt(baris, 0).toString());
        txtMerk.setText(tbKendaraan.getValueAt(baris, 1).toString());
        cbJenis.setSelectedItem(tbKendaraan.getValueAt(baris, 2).toString());
        txtHarga.setText(tbKendaraan.getValueAt(baris, 3).toString());
        
        // Kunci Plat Nomor (karena nopol adalah Primary Key) agar tidak bisa diubah saat mode update
        txtPlat.setEnabled(false); 
    }
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_tbKendaraanMouseClicked


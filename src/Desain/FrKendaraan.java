    private void tampilTable() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("No. Polisi");
        model.addColumn("Merk Kendaraan");
        model.addColumn("Jenis");
        model.addColumn("Harga Sewa");
        model.addColumn("Status"); 
        
        try {
            java.sql.Connection conn = new myConnection.DB0().getConnection();
            java.sql.Statement st = conn.createStatement();
            String sql = "SELECT * FROM tb_kendaraan";
            java.sql.ResultSet rs = st.executeQuery(sql);
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("nopol"),
                    rs.getString("merk_kendaraan"),
                    rs.getString("jenis"),
                    rs.getString("harga_sewa"),
                    rs.getString("status")
                });
            }
            tbKendaraan.setModel(model); 
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }

